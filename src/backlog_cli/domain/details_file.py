"""The details file of one item: a managed title line and eight `##` sections."""

import re
from collections.abc import Iterator
from dataclasses import dataclass, field

from backlog_cli.domain.vocabulary import DetailsSection
from backlog_cli.errors import UsageError


@dataclass(frozen=True)
class DetailsLine:
    section: str | None  # heading the line belongs to; None before the first one
    number: int  # 1-based line number in the file
    text: str
    is_heading: bool


@dataclass
class RawSection:
    name: str
    lines: list[str] = field(default_factory=list)


class DetailsFile:
    HEADING_PATTERN = re.compile(r"^ {0,3}##[ \t]+(.+?)\s*$")
    MAX_BYTES = 256 * 1024

    def __init__(self, sections: dict[DetailsSection, str]) -> None:
        self.sections = sections

    @classmethod
    def create_blank(cls) -> "DetailsFile":
        return cls({section: "" for section in DetailsSection})

    @classmethod
    def read_lines(cls, text: str) -> Iterator[DetailsLine]:
        """Every line with its section."""
        section = None
        for number, line in enumerate(text.splitlines(), start=1):
            heading = cls.HEADING_PATTERN.match(line)
            if heading:
                section = heading[1]
            yield DetailsLine(section, number, line, heading is not None)

    @classmethod
    def parse(cls, text: str, is_user_text: bool = False) -> "DetailsFile":
        """Split by `##` headings.

        The stored file starts with the generated title line. In text given by
        the user a line starting with `# ` before the first section is refused:
        the title line is generated by the CLI.
        """
        found: list[RawSection] = []
        for line in cls.read_lines(text):
            if line.is_heading:
                found.append(RawSection(line.section))
            elif found:
                found[-1].lines.append(line.text)
            elif line.text.startswith("# "):
                if is_user_text:
                    raise UsageError(
                        f"line {line.number} starts with '# ': the title line is "
                        "generated by backlog from the id and the title; remove it"
                    )
            elif line.text.strip():
                raise UsageError(
                    "text before the first '## ' heading; "
                    "start with the first section heading"
                )
        problems = cls._find_heading_problems([raw.name for raw in found])
        if problems:
            raise UsageError(
                "The details must have exactly these headings, "
                "once each, in this order:\n"
                + "\n".join(f"  ## {section}" for section in DetailsSection)
                + "\nProblems:\n"
                + "\n".join(f"  {problem}" for problem in problems)
            )
        return cls(
            {
                DetailsSection(raw.name): "\n".join(raw.lines).strip("\n")
                for raw in found
            }
        )

    @staticmethod
    def _find_heading_problems(names: list[str]) -> list[str]:
        known = [str(section) for section in DetailsSection]
        distinct = list(dict.fromkeys(names))
        problems = [f"missing heading: {name}" for name in known if name not in names]
        problems += [
            f"unknown heading: {name}" for name in distinct if name not in known
        ]
        problems += [
            f"repeated heading: {name}" for name in distinct if names.count(name) > 1
        ]
        if not problems and names != known:
            problems.append("headings are in the wrong order")
        return problems

    @staticmethod
    def parse_section_name(name: str) -> DetailsSection:
        try:
            return DetailsSection(name)
        except ValueError:
            raise UsageError(
                f"unknown section {name!r}; sections are:\n"
                + "\n".join(f"  {section}" for section in DetailsSection)
            ) from None

    def get_section(self, section: DetailsSection) -> str:
        return self.sections[section]

    def append_text(self, section: DetailsSection, text: str) -> None:
        """Add a new paragraph at the end of the section."""
        text = text.strip()
        self._require_safe_text(text)
        body = self.sections[section]
        self.sections[section] = f"{body}\n\n{text}" if body else text

    def replace_text(self, section: DetailsSection, text: str) -> None:
        """Make the text the whole content of the section."""
        text = text.strip()
        self._require_safe_text(text)
        self.sections[section] = text

    def _require_safe_text(self, text: str) -> None:
        """A `## ` line would split the file."""
        if any(line.is_heading for line in self.read_lines(text)):
            raise UsageError(
                "the text has a line starting with '## '; it would split the section"
            )

    @classmethod
    def require_size(cls, text: str) -> None:
        size = len(text.encode())
        if size > cls.MAX_BYTES:
            raise UsageError(
                f"the details file would be {size // 1024} KB ({size} bytes); "
                f"at most {cls.MAX_BYTES // 1024} KB"
            )

    def render(self, item_id: str, title: str, empty_mark: str = "") -> str:
        """The file text; `empty_mark` fills a section without text (for readers)."""
        parts = [f"# {item_id}: {title}"]
        parts += [
            f"## {name}\n\n{body or empty_mark}" if body or empty_mark else f"## {name}"
            for name, body in self.sections.items()
        ]
        return "\n\n".join(parts) + "\n"
